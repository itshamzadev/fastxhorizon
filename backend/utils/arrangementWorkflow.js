const transitions = {
  PENDING_REVIEW: ['CHECKING_AVAILABILITY', 'AVAILABLE_AWAITING_ADVANCE', 'AVAILABLE_CONFIRMED', 'NOT_AVAILABLE', 'REJECTED', 'CANCELLED'],
  CHECKING_AVAILABILITY: ['AVAILABLE_AWAITING_ADVANCE', 'AVAILABLE_CONFIRMED', 'NOT_AVAILABLE', 'REJECTED', 'CANCELLED'],
  AVAILABLE_AWAITING_ADVANCE: ['ADVANCE_SUBMITTED', 'CANCELLED'],
  AVAILABLE_CONFIRMED: ['ADVANCE_PENDING', 'AVAILABLE_AWAITING_ADVANCE', 'CANCELLED'],
  ADVANCE_PENDING: ['ADVANCE_SUBMITTED', 'CANCELLED'],
  ADVANCE_SUBMITTED: ['ADVANCE_VERIFIED', 'AVAILABLE_AWAITING_ADVANCE', 'ADVANCE_PENDING', 'CANCELLED'],
  ADVANCE_VERIFIED: ['ORDERED_FROM_SUPPLIER', 'SOURCING', 'CANCELLED', 'REFUND_PENDING'],
  ORDERED_FROM_SUPPLIER: ['PRODUCT_ARRIVED', 'NOT_AVAILABLE', 'REFUND_PENDING', 'CANCELLED'],
  SOURCING: ['PRODUCT_ARRIVED', 'READY_TO_DISPATCH', 'NOT_AVAILABLE', 'REFUND_PENDING', 'CANCELLED'],
  PRODUCT_ARRIVED: ['READY_FOR_DELIVERY'],
  READY_FOR_DELIVERY: ['SHIPPED'],
  READY_TO_DISPATCH: ['SHIPPED'],
  SHIPPED: ['DELIVERED'],
  DELIVERED: ['COMPLETED'],
  REFUND_PENDING: ['REFUNDED'],
};
function canTransition(from, to) { return from === to || (transitions[from] || []).includes(to); }
module.exports = { transitions, canTransition };

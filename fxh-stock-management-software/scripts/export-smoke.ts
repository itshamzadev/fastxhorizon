import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { openDatabase, addProduct, exportCatalog } from '../electron/database';

const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'fxh-export-'));
const db = openDatabase(dir);
const now = new Date().toISOString();
db.prepare('INSERT INTO brands(id,name,active,created_at,updated_at) VALUES(?,?,?,?,?)').run('brand-1', 'Gul Ahmed', 1, now, now);
db.prepare('INSERT INTO categories(id,name,slug,active,created_at,updated_at) VALUES(?,?,?,?,?,?)').run('cat-1', 'Clothing', 'clothing', 1, now, now);
fs.mkdirSync(path.join(dir, 'media', 'products'), { recursive: true });
fs.writeFileSync(path.join(dir, 'media', 'products', 'test.webp'), Buffer.from('test-image-data'));
addProduct(db, { sku: 'INTERNAL-MODEL-001', modelName: 'INTERNAL-MODEL-001', name: 'Test Shirt', category: 'Clothing', brandName: 'Gul Ahmed', fabricMaterial: 'Cotton', description: 'Test description', colors: [{ sku: 'INTERNAL-MODEL-001-BLUE', color: 'Blue', quantity: 3, unitCost: 1200, sellingPrice: 1800, originalPrice: 2200, images: ['media/products/test.webp'] }] });
addProduct(db, { sku: 'INTERNAL-MODEL-002', modelName: 'INTERNAL-MODEL-002', name: 'Test Shirt', category: 'Clothing', brandName: 'Gul Ahmed', fabricMaterial: 'Cotton', description: 'Second distinct item', colors: [{ sku: 'INTERNAL-MODEL-002-RED', color: 'Red', quantity: 1, unitCost: 1000, sellingPrice: 1500, originalPrice: 1500, images: ['media/products/test.webp'] }] });
const result = exportCatalog(db) as any;
assert.equal(result.products.length, 2);
assert.equal(result.products.every((product: any) => product.brandId === 'brand-1'), true);
assert.equal(result.products.every((product: any) => !('clothingType' in product)), true);
const discountedProduct = result.products.find((product: any) => product.discountAmount === 400);
const discountedVariant = result.variants.find((variant: any) => variant.price === 1800);
assert.equal(discountedProduct.quantity, 3);
assert.equal(discountedVariant.price, 1800);
assert.equal(discountedProduct.discountAmount, 400);
assert.equal(discountedProduct.discountPercentage, 18.18);
assert.equal(result.products[0].sku.startsWith('FXH-WEB-P-'), true);
assert.equal(result.variants[0].sku.startsWith('FXH-WEB-V-'), true);
assert.equal(result.products.some((product: any) => product.sku.includes('INTERNAL-MODEL')), false);
assert.equal(new Set(result.products.map((product: any) => product.sku)).size, 2);
assert.equal(new Set(result.products.map((product: any) => product.slug)).size, 2);
assert.equal(result.products.every((product: any) => product.images[0] === 'media/products/test.webp'), true);
assert.equal(fs.existsSync(path.join(dir, result.products[0].images[0])), true);
assert.equal('unit_cost' in result.products[0], false);
assert.equal('unit_cost' in result.variants[0], false);
db.close();
fs.rmSync(dir, { recursive: true, force: true });
console.log('Website export smoke test passed: image attachment, privacy-safe identifiers, duplicate names, brand, discount, quantity and pricing verified.');
